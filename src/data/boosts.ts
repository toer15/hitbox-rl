function buildBoosts(): Boost[] {
  const used = new Map<string, number>();
  const boosts: Boost[] = [];

  for (const [name, tone] of RAW_BOOSTS) {
    const base = slugify(name);
    const seen = used.get(base) ?? 0;
    used.set(base, seen + 1);
    boosts.push({
      id: seen === 0 ? base : `${base}-${seen + 1}`,
      name,
      tone,
    });
  }

  return boosts.sort((a, b) => a.name.localeCompare(b.name));
}

export const BOOSTS = buildBoosts();

export function getBoost(id: string | null): Boost | undefined {
  if (!id) return undefined;
  return BOOSTS.find((boost) => boost.id === id);
}
